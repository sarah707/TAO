  function getEffectRandomRange(afterText, eventName) {
    const match = String(afterText || '').match(/随机(\d+)到(\d+)/);
    if (match) {
      return { min: Number(match[1]), max: Number(match[2]) };
    }
    if (eventName.includes('辩论') || eventName === '校园音乐节事件') {
      return { min: 1, max: 5 };
    }
    return { min: 1, max: 10 };
  }

  function buildEventEffects(afterText, eventName = '') {
    const source = String(afterText || '').trim();
    if (!source || source === '无') {
      return [];
    }

    const effects = [];
    const range = getEffectRandomRange(source, eventName);
    const sign = source.includes('好感度-') ? -1 : 1;
    const addFavorability = (targets, overrideRange = range) => {
      effects.push({
        type: 'favorability',
        targets,
        min: overrideRange.min,
        max: overrideRange.max,
        sign
      });
    };

    if (source.includes('所有参与角色') || source.includes('所有传入角色')) {
      addFavorability('participants');
      if (source.includes('与新建角色')) {
        addFavorability('new-characters');
      }
    } else if (source.includes('两个传入角色好感度')) {
      addFavorability('first-two-context');
    } else if (source.includes('这两个角色好感度') || source.includes('两个角色好感度')) {
      addFavorability('first-two-new-or-participants');
    } else if (source.includes('恋人好感度')) {
      addFavorability('first-lover');
    } else if (source.includes('角色好感度+10')) {
      addFavorability('first-new-or-participant', { min: 10, max: 10 });
    } else if (source.includes('该角色好感度')) {
      addFavorability('first-new-or-participant');
    } else if (source.includes('上司好感度') || source.includes('教授好感度') || source.includes('学弟好感度')) {
      addFavorability('first-new');
    } else if (source.includes('角色好感度+随机')) {
      addFavorability('first-participant');
    }

    if (source.includes('开启做学生会秘书的行程')) {
      effects.push({ type: 'unlock-action', action: 'student-secretary' });
    }
    if (source.includes('角色标记为恋人')) {
      effects.push({ type: 'set-lover', targets: 'first-participant' });
    }
    if (source.includes('三人约会参与者')) {
      effects.push({ type: 'set-character-flag', targets: 'first-two-context', flag: '三人约会参与者' });
    }
    if (source.includes('发传单认识的人')) {
      effects.push({ type: 'set-character-flag', targets: 'new-characters', flag: '发传单认识的人' });
    }
    if (source.includes('家教学生') || source.includes('家教学生的家长')) {
      effects.push({ type: 'assign-tutor-roles' });
    }
    if (source.includes('做助教认识的学弟')) {
      effects.push({ type: 'set-character-flag', targets: 'new-characters', flag: '做助教认识的学弟' });
    }
    if (source.includes('实习上司')) {
      effects.push({ type: 'set-character-flag', targets: 'new-characters', flag: '实习上司' });
    }
    if (source.includes('辩论队队友')) {
      effects.push({ type: 'set-character-flag', targets: 'participants-and-new', flag: '辩论队队友' });
    }
    return effects;
  }

